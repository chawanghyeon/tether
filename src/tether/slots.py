import dataclasses
import fcntl
import json
import os
import re
import subprocess
from collections.abc import Iterator, Mapping, Sequence
from contextlib import contextmanager
from pathlib import Path

from tether.config import Config

MAIN_SLOT = 0
REGISTRY_DIR = "tether"
REGISTRY_FILE = "slots.json"
REGISTRY_LOCK = "slots.lock"
SETUP_HINT = "tether slot setup"
GENERATED_HEADER = "# generated by `tether slot env`; safe to overwrite"
TEMPLATE_FIELD = re.compile(r"\{\s*(?:(\d+)\s*\+\s*)?(slot|name)\s*\}")
ENV_LINE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$")


class SlotError(RuntimeError):
    pass


@dataclasses.dataclass(frozen=True)
class Worktree:
    path: Path
    is_main: bool


@dataclasses.dataclass(frozen=True)
class Slot:
    number: int
    worktree: Worktree
    values: dict[str, str]


def render(template: str, slot: int, name: str) -> str:
    def substitute(match: re.Match[str]) -> str:
        offset, field = match.groups()
        if field == "name":
            return name
        return str(int(offset or 0) + slot)

    return TEMPLATE_FIELD.sub(substitute, template)


def render_all(
    templates: Mapping[str, str], slot: int, name: str
) -> dict[str, str]:
    return {key: render(value, slot, name) for key, value in templates.items()}


def list_worktrees(root: Path) -> list[Worktree]:
    output = _git(root, "worktree", "list", "--porcelain")
    paths = [
        Path(line.removeprefix("worktree ")).resolve()
        for line in output.splitlines()
        if line.startswith("worktree ")
    ]
    return [Worktree(path, index == 0) for index, path in enumerate(paths)]


def current_worktree(root: Path) -> Worktree:
    top = Path(_git(root, "rev-parse", "--show-toplevel").strip()).resolve()
    for worktree in list_worktrees(root):
        if worktree.path == top:
            return worktree
    raise SlotError(f"{top} is not a git worktree")


def assign_slot(config: Config) -> Slot:
    worktree = current_worktree(config.root)
    if worktree.is_main:
        return _slot(config, MAIN_SLOT, worktree)
    with _registry(config.root) as registry:
        key = str(worktree.path)
        if key not in registry:
            registry[key] = _free_slot(registry, config.max_slots)
        number = registry[key]
    return _slot(config, number, worktree)


def existing_slot(config: Config) -> Slot | None:
    worktree = current_worktree(config.root)
    if worktree.is_main:
        return _slot(config, MAIN_SLOT, worktree)
    number = registered_slots(config.root).get(worktree.path)
    return None if number is None else _slot(config, number, worktree)


def release_slot(config: Config) -> int | None:
    worktree = current_worktree(config.root)
    with _registry(config.root) as registry:
        return registry.pop(str(worktree.path), None)


def registered_slots(root: Path) -> dict[Path, int]:
    with _registry(root) as registry:
        return {Path(path): number for path, number in registry.items()}


def parse_env(text: str) -> dict[str, str]:
    values = {}
    for line in text.splitlines():
        match = ENV_LINE.match(line)
        if match and not line.lstrip().startswith("#"):
            values[match.group(1)] = match.group(2).strip()
    return values


def merge_env(base: str, overrides: Mapping[str, str]) -> str:
    remaining = dict(overrides)
    lines = [GENERATED_HEADER]
    for line in base.splitlines():
        if line.strip() == GENERATED_HEADER:
            continue
        match = ENV_LINE.match(line)
        if match and match.group(1) in remaining:
            key = match.group(1)
            lines.append(f"{key}={remaining.pop(key)}")
        else:
            lines.append(line)
    lines.extend(f"{key}={value}" for key, value in remaining.items())
    return "\n".join(lines) + "\n"


def write_env(config: Config, slot: Slot, force: bool = False) -> Path | None:
    if slot.worktree.is_main:
        return None
    target = slot.worktree.path / config.slot_env_file
    if target.exists() and not force and not _is_generated(target):
        raise SlotError(
            f"{target} was not made by tether; use --force to overwrite"
        )
    main = next(w for w in list_worktrees(config.root) if w.is_main)
    base_file = main.path / config.slot_env_file
    base = base_file.read_text() if base_file.is_file() else ""
    target.write_text(merge_env(base, slot.values))
    return target


def run_slot_command(
    config: Config, slot: Slot, command: Sequence[str]
) -> subprocess.CompletedProcess[str] | None:
    if not command:
        return None
    name = slot.worktree.path.name
    rendered = [render(part, slot.number, name) for part in command]
    return subprocess.run(
        rendered,
        cwd=slot.worktree.path,
        env={**os.environ, **slot.values},
        capture_output=True,
        text=True,
    )


def doctor(config: Config) -> list[str]:
    problems = []
    registry = registered_slots(config.root)
    seen: dict[tuple[str, str], list[Path]] = {}
    for worktree in list_worktrees(config.root):
        env_file = worktree.path / config.slot_env_file
        if not worktree.is_main and worktree.path not in registry:
            problems.append(f"{worktree.path}: no slot; run `{SETUP_HINT}`")
        if not env_file.is_file():
            if config.slot_env and not worktree.is_main:
                problems.append(f"{worktree.path}: missing {env_file.name}")
            continue
        values = parse_env(env_file.read_text())
        for key in config.slot_env:
            if key in values:
                seen.setdefault((key, values[key]), []).append(worktree.path)
    for (key, value), paths in sorted(seen.items()):
        if len(paths) > 1:
            names = ", ".join(str(path) for path in paths)
            problems.append(f"{key}={value} is shared by {names}")
    return problems


def _slot(config: Config, number: int, worktree: Worktree) -> Slot:
    values = render_all(config.slot_env, number, worktree.path.name)
    return Slot(number, worktree, values)


def _free_slot(registry: Mapping[str, int], max_slots: int) -> int:
    used = set(registry.values()) | {MAIN_SLOT}
    for number in range(1, max_slots):
        if number not in used:
            return number
    raise SlotError(f"all {max_slots} slots are in use")


def _is_generated(path: Path) -> bool:
    with path.open() as handle:
        return handle.readline().strip() == GENERATED_HEADER


@contextmanager
def _registry(root: Path) -> Iterator[dict[str, int]]:
    common = Path(
        _git(
            root, "rev-parse", "--path-format=absolute", "--git-common-dir"
        ).strip()
    )
    directory = common / REGISTRY_DIR
    directory.mkdir(exist_ok=True)
    live = {str(worktree.path) for worktree in list_worktrees(root)}
    with open(directory / REGISTRY_LOCK, "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        path = directory / REGISTRY_FILE
        try:
            stored = json.loads(path.read_text())
        except (FileNotFoundError, json.JSONDecodeError):
            stored = {}
        registry = {
            key: int(value) for key, value in stored.items() if key in live
        }
        yield registry
        path.write_text(json.dumps(registry, indent=2, sort_keys=True))


def _git(root: Path, *args: str) -> str:
    try:
        completed = subprocess.run(
            ("git", *args), cwd=root, capture_output=True, text=True
        )
    except FileNotFoundError as error:
        raise SlotError("git not found") from error
    if completed.returncode != 0:
        raise SlotError(completed.stderr.strip() or "not a git repository")
    return completed.stdout
